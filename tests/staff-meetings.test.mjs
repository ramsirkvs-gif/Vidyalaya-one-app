import test from 'node:test';
import assert from 'node:assert/strict';
import {taskFixture} from './task-manager-fixture.mjs';

test('Principal assigns a writer, whose verified PIN saves printable minutes and attendance',async()=>{
 const f=taskFixture(),meetingId='f'.repeat(32);
 const {viewerToken}=await f.service('remember-view',{},'principal');
 const call=(action,input,token='')=>f.service(action,input,token,'synthetic-meeting-ip',{viewerToken});
 const principal=(meetingOperation,extra={})=>call('staff-meetings-principal',{meetingId,meetingOperation,...extra},'principal');
 const pin=(staffId,code,meetingOperation,extra={})=>call('pin-submit',{operation:'staff-meetings',meetingId,staffId,pin:code,meetingOperation,...extra});
 const writerId='X:one',otherId='X:two';
 for(const [staffId,pin]of [[writerId,'123'],[otherId,'456']])await call('set-pin',{staffId,pin},'principal');
 await assert.rejects(f.service('staff-meetings-read',{}),/viewing password/);
 await assert.rejects(call('staff-meetings-principal',{meetingOperation:'create',meetingId,writerId},'outsider'),/Principal/);
 await principal('create',{writerId});
 const list=await call('staff-meetings-read',{});
 assert.equal(list.meetings.length,1);
 assert.ok(list.meetings[0].createdAt>0);
 assert.equal(list.meetings[0].writerId,writerId);
 await assert.rejects(call('staff-meetings-read',{meetingId}),/not been saved/);
 await assert.rejects(pin(otherId,'456','read'),/Principal-assigned/);
 await assert.rejects(pin(writerId,'999','read'),/PIN/);
 const {meeting}=await pin(writerId,'123','read');
 assert.ok(meeting.roster.some(person=>person.id==='principal'));
 const attendance=Object.fromEntries(meeting.roster.map(person=>[person.id,person.id===otherId?'absent':'present']));
 const values={expectedRevision:meeting.revision,agenda:'Department review\n1. Follow-up duties',minutes:'The staff agreed to complete the review by Friday.',attendance};
 await assert.rejects(pin(writerId,'123','save',{...values,attendance:{}}),/Mark each/);
 await pin(writerId,'123','save',values);
 const {report}=await call('staff-meetings-read',{meetingId});
 assert.equal(report.agenda,values.agenda);assert.equal(report.minutes,values.minutes);
 assert.deepEqual(report.absent.map(person=>person.name),['Synthetic Teacher two']);
 assert.ok(report.present.some(person=>person.name==='Synthetic Teacher one'));
 assert.ok(!Object.hasOwn(report,'attendance'));
 await assert.rejects(pin(writerId,'123','save',values),/changed/);
 const admin=(await principal('read')).meetings[0];
 await principal('assign',{writerId:otherId,expectedRevision:admin.revision});
 await assert.rejects(pin(writerId,'123','read'),/Principal-assigned/);
 assert.equal((await pin(otherId,'456','read')).meeting.minutes,values.minutes);
 assert.equal((await call('staff-meetings-read',{meetingId})).report.writerName,'Synthetic Teacher one');
});
