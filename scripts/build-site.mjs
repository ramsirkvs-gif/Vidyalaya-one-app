import {prepareMCQAssets} from './prepare-mcq-assets.mjs';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const output=path.join(root,'public');
await prepareMCQAssets();
try {
 const files=await fs.readdir(output);
 if(files.length&&!files.includes('.vidyalaya-build'))throw Error('Refusing to replace an existing public directory that was not generated by this build.');
 await fs.rm(output,{recursive:true});
} catch(error) { if(error.code!=='ENOENT')throw error; }
await fs.mkdir(output,{recursive:true});
const hash=createHash('sha256');
// Delivery changes must also trigger the live-update watcher.
hash.update('scripts/build-site.mjs');hash.update(await fs.readFile(path.join(root,'scripts/build-site.mjs')));
async function copy(relative){
 const source=path.join(root,relative),target=path.join(output,relative);
 if((await fs.stat(source)).isDirectory()){
  await fs.mkdir(target,{recursive:true});
  for(const name of (await fs.readdir(source)).sort())await copy(path.join(relative,name));
 }else{
  const bytes=await fs.readFile(source);hash.update(relative);hash.update(bytes);await fs.writeFile(target,bytes);
 }
}
for(const name of (await fs.readdir(root)).sort()){
 if(name==='index.html'||/^cbse-[\w-]+\.(html|js|css)$/.test(name)||['cbse-board-datesheet-2027.pdf','firebase-client.js','portal-firebase.js','live-update.js','cbse.css','database.rules.json'].includes(name)||/\.(png|svg|ico)$/.test(name)||/^portal-tile-[\w-]+\.jpe?g$/.test(name))await copy(name);
}
await copy('cbse-team-x-weekly');
await copy('vendor');
const version=hash.digest('hex');
for(const name of await fs.readdir(output))if(name.endsWith('.html')){
 const p=path.join(output,name);const html=await fs.readFile(p,'utf8');
 // A new document must not reuse an older entry script or stylesheet after deployment.
 // Query versions leave URLs, hashes, authentication and the active-form update guard intact.
 const updated=html.replace(/\b(src|href)="([^"/?#]+\.(?:js|css))"/g,(_,attribute,asset)=>`${attribute}="${asset}?v=${version}"`);
 await fs.writeFile(p,updated);
}
// Version first-party imports too: new entry scripts must not reuse an older child module.
for(const name of await fs.readdir(output))if(name.endsWith('.js')){
 const p=path.join(output,name),source=await fs.readFile(p,'utf8');
 const updated=source.replace(/(['"])(\.\/(?:cbse-[\w-]+|firebase-client|portal-firebase|live-update)\.js)\1/g,(_,quote,asset)=>quote+asset+'?v='+version+quote);
 await fs.writeFile(p,updated);
}
await fs.writeFile(path.join(output,'app-version.json'),JSON.stringify({version})+'\n');
await fs.writeFile(path.join(output,'.vidyalaya-build'),'Generated by scripts/build-site.mjs\n');
console.log(`Built website with deployment version ${version.slice(0,12)}. Private imports and development files are excluded.`);
